"""Conformance of the Python implementation against the Java reference.

The corpus in ``cases/`` is the port specification. Each case holds a
``config.yaml`` (the canonical input), ``case.yaml`` (metadata) and
``expected/`` (reference output generated by the Java implementation, see
``generate.py``).

Two tiers:

``A``
    Reproducible, and compared field by field at the tier A tolerance. Every
    case is tier A, escape modelling included: the port draws from
    ``java.util.Random`` in the Java's order, so with the case's seed it
    reproduces the Java's result rather than only its statistics.
``B``
    For a calculation that cannot be reproduced draw for draw, so only loose
    agreement is meaningful. No case uses it at present.

Every case runs; none is excused. A case the port cannot run fails.

Tolerances come from ``MANIFEST.yaml`` and are set by how well conditioned
the calculation is, not by how carefully the port was written; the manifest's
``tolerance_rationale`` records the measurements behind each one.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
import yaml
from _agreement import record_agreement, record_array_agreement
from _array_stats import compare as compare_arrays
from _array_stats import from_simulation

from pyraddose_3d.models.experiment import Experiment
from pyraddose_3d.solve import simulate, solve

HERE = Path(__file__).parent
CASES_DIR = HERE / "cases"
MANIFEST_PATH = HERE / "MANIFEST.yaml"

pytestmark = pytest.mark.conformance


def manifest() -> dict[str, Any]:
    """Corpus-wide metadata and tolerances."""
    return yaml.safe_load(MANIFEST_PATH.read_text(encoding="utf-8"))


def case_dirs() -> list[Path]:
    """Every case directory, in id order."""
    return sorted(p for p in CASES_DIR.iterdir() if p.is_dir())


def load_case(path: Path) -> tuple[dict[str, Any], Experiment, list[dict[str, float]]]:
    """Load one case's metadata, configuration and reference summary."""
    meta = yaml.safe_load((path / "case.yaml").read_text(encoding="utf-8"))
    experiment = Experiment.from_yaml(path / "config.yaml")
    summary = json.loads((path / "expected" / "summary.json").read_text("utf-8"))
    return meta, experiment, summary


CASE_DIRS = case_dirs()
CASE_IDS = [p.name for p in CASE_DIRS]


# --------------------------------------------------------------------------
# Corpus integrity. These must pass now -- they check the specification
# itself, not the implementation.
# --------------------------------------------------------------------------


def test_the_corpus_is_not_empty() -> None:
    assert CASE_DIRS, f"no conformance cases found in {CASES_DIR}"


def test_manifest_matches_the_cases_on_disk() -> None:
    assert manifest()["case_count"] == len(CASE_DIRS)


@pytest.mark.parametrize("case_dir", CASE_DIRS, ids=CASE_IDS)
def test_case_config_is_valid_and_complete(case_dir: Path) -> None:
    """Every case must load, validate, and carry a non-empty reference."""
    meta, experiment, summary = load_case(case_dir)

    assert meta["tier"] in {"A", "B"}
    assert meta["exercises"], "every case must say what it is for"
    assert summary, "reference summary is empty"
    assert len(summary) == len(experiment.wedges), (
        "reference has a different number of wedges than the configuration"
    )


@pytest.mark.parametrize("case_dir", CASE_DIRS, ids=CASE_IDS)
def test_case_round_trips_through_the_legacy_emitter(case_dir: Path) -> None:
    """The .txt handed to the reference is derived from this same config.

    If emission is not deterministic, the reference outputs do not correspond
    to the committed configuration and every conformance result below is
    meaningless.
    """
    _, experiment, _ = load_case(case_dir)
    assert experiment.to_raddose_txt() == experiment.to_raddose_txt()
    assert "Crystal" in experiment.to_raddose_txt()


def test_random_cases_carry_their_seed() -> None:
    """A case with escape modelling is only reproducible with its seed."""
    for case_dir in CASE_DIRS:
        meta, experiment, _ = load_case(case_dir)
        if experiment.crystal.escape.any_enabled:
            assert experiment.seed is not None, case_dir.name
            assert meta["seed"] == experiment.seed


# --------------------------------------------------------------------------
# The conformance comparison itself.
# --------------------------------------------------------------------------


def compute_summary(experiment: Experiment) -> list[dict[str, float]]:
    """Run the Python implementation and return a comparable summary.

    Parameters
    ----------
    experiment : Experiment
        The case configuration.

    Returns
    -------
    list[dict[str, float]]
        One dict per wedge, keyed as the reference JSON is.
    """
    return [summary.as_dict() for summary in solve(experiment)]


def tolerance_for(tier: str, field: str, manifest_data: dict[str, Any]) -> float:
    """Relative tolerance for one field of one tier.

    Parameters
    ----------
    tier : str
        ``"A"`` or ``"B"``.
    field : str
        Summary field name.
    manifest_data : dict[str, Any]
        The parsed manifest.

    Returns
    -------
    float
        Relative tolerance.
    """
    tolerances = manifest_data["tolerances"]
    if tier == "B":
        return float(tolerances["tier_B_relative"])
    if field in set(manifest_data["quantised_quantities"]):
        return float(tolerances["tier_A_quantised_quantities_relative"])
    return float(tolerances["tier_A_relative"])


CASE_PARAMS = [pytest.param(case_dir, id=case_dir.name) for case_dir in CASE_DIRS]


@pytest.mark.parametrize("case_dir", CASE_PARAMS)
def test_matches_reference(case_dir: Path) -> None:
    """Compare the Python result against the Java reference.

    Reports the worst relative deviation seen, not merely pass/fail: a case
    sitting just inside tolerance is telling you something that a green tick
    would hide.
    """
    meta, experiment, expected = load_case(case_dir)
    actual = compute_summary(experiment)
    tolerances = manifest()

    assert len(actual) == len(expected)

    worst_field, worst_deviation = "", 0.0
    failures: list[str] = []
    for index, (exp_row, act_row) in enumerate(zip(expected, actual, strict=True)):
        for field, exp_value in exp_row.items():
            act_value = act_row[field]
            scale = max(abs(exp_value), 1e-30)
            deviation = abs(act_value - exp_value) / scale
            if deviation > worst_deviation:
                worst_field, worst_deviation = f"wedge {index} {field}", deviation
            limit = tolerance_for(meta["tier"], field, tolerances)
            if deviation > limit:
                failures.append(
                    f"wedge {index} {field}: expected {exp_value!r}, got "
                    f"{act_value!r} (relative {deviation:.3e} > {limit:.1e})"
                )

    record_agreement(case_dir.name, worst_deviation, worst_field)
    assert not failures, "\n".join(failures)


@pytest.mark.parametrize("case_dir", CASE_PARAMS)
def test_arrays_match_reference(case_dir: Path) -> None:
    """Compare the dose field and the per-image series, not just the totals.

    The sixteen summary numbers are averages and extremes over the whole
    crystal and wedge, so they cannot see a dose that is right in total but
    in the wrong place, or right at the end but wrong along the way. These
    statistics can: the dose-weighted centroid moves if the field is
    mirrored, and the per-image series move if dose arrives at the wrong
    time. See ``_array_stats`` for what each one is, and the manifest's
    ``array_tolerance_rationale`` for how the limits were measured.
    """
    _, experiment, _ = load_case(case_dir)
    expected = json.loads(
        (case_dir / "expected" / "array_stats.json").read_text("utf-8")
    )
    actual = from_simulation(simulate(experiment, record_images=True))

    failures, achieved = compare_arrays(
        expected, actual, manifest()["array_tolerances"]
    )

    used = [
        (
            deviation / limit if limit else (0.0 if deviation == 0 else float("inf")),
            label,
        )
        for label, deviation, limit in achieved
    ]
    fraction, statistic = max(used, default=(0.0, ""))
    record_array_agreement(case_dir.name, fraction, statistic)
    assert not failures, "\n".join(failures)


def test_every_array_statistic_has_a_tolerance() -> None:
    """A statistic without a measured tolerance is an error, not a default.

    Checked against the corpus as a whole, so adding a statistic to the
    reducers without adding its tolerance to the manifest fails here rather
    than in whichever case happens to run first.
    """
    from _array_stats import DEFERRED, _leaves, tolerance_for

    tolerances = manifest()["array_tolerances"]
    seen = set()
    for case_dir in CASE_DIRS:
        stats = json.loads(
            (case_dir / "expected" / "array_stats.json").read_text("utf-8")
        )
        for path, _ in _leaves(stats):
            if (path[0], path[-1]) in DEFERRED:
                continue
            tolerance_for(path, tolerances)
            seen.add("/".join(path))
    assert seen, "the corpus has no array statistics"


def test_arrays_see_a_mirrored_dose_field_the_summary_cannot(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    """Why the array statistics exist, pinned so it cannot quietly stop being true.

    Rotating the crystal the wrong way mirrors the dose field. Every summary
    number is an average, sum or extreme over the crystal, and so is
    unchanged by a mirror -- for the cylinder case, whose voxel set is
    symmetric about the rotation axis, all sixteen stay within tolerance.
    The dose-weighted centroid does not: it flips sign exactly, from
    +0.00498 um to -0.00498 um across the axis.

    In the other cases reversing the rotation also changes the totals,
    because the half-open occupancy test leaves their voxel sets slightly
    lopsided, so the summary catches it there too. The cylinder is the case
    where only the position of the dose gives it away.
    """
    import pyraddose_3d.solve as solve_module

    real = solve_module.exposure_angles
    monkeypatch.setattr(
        solve_module,
        "exposure_angles",
        lambda *args, **kwargs: [-angle for angle in real(*args, **kwargs)],
    )

    case_dir = CASES_DIR / "011-crystal-cylinder"
    _, experiment, _ = load_case(case_dir)
    expected = json.loads(
        (case_dir / "expected" / "array_stats.json").read_text("utf-8")
    )
    mirrored = from_simulation(simulate(experiment, record_images=True))

    failures, _ = compare_arrays(expected, mirrored, manifest()["array_tolerances"])

    assert any(f.startswith("DoseState/dose_centroid") for f in failures), (
        "reversing the rotation should move the dose centroid past tolerance"
    )
