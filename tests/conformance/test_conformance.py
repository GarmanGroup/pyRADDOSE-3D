"""Conformance of the Python implementation against the Java reference.

The corpus in ``cases/`` is the port specification. Each case holds a
``config.yaml`` (the canonical input), ``case.yaml`` (metadata) and
``expected/`` (reference output generated by the Java implementation, see
``generate.py``).

Two tiers, because Monte Carlo cannot be compared value by value:

``A``
    Deterministic. Compared field by field at the tier A tolerance.
``B``
    Escape modelling enabled. The reference consumes random draws in an order
    a vectorised implementation cannot reproduce, so only loose agreement is
    meaningful.

Cases the port does not cover are ``xfail``, not skips -- a skipped test is
invisible, an xfail is a visible, counted reminder -- and the marker is
derived from the configuration rather than a hand-kept list, so a case cannot
stay excused after the gap it names is filled. ``strict`` means an xpass
fails: when escape or the Leal model lands, these turn red and say so.

Tolerances come from ``MANIFEST.yaml`` and are set by how well conditioned
the calculation is, not by how carefully the port was written; the manifest's
``tolerance_rationale`` records the measurements behind each one.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pytest
import yaml
from _agreement import record_agreement

from pyraddose_3d.models.experiment import Experiment
from pyraddose_3d.solve import solve

HERE = Path(__file__).parent
CASES_DIR = HERE / "cases"
MANIFEST_PATH = HERE / "MANIFEST.yaml"

pytestmark = pytest.mark.conformance


def manifest() -> dict[str, Any]:
    """Corpus-wide metadata and tolerances."""
    return yaml.safe_load(MANIFEST_PATH.read_text(encoding="utf-8"))


def case_dirs() -> list[Path]:
    """Every case directory, in id order."""
    return sorted(p for p in CASES_DIR.iterdir() if p.is_dir())


def load_case(path: Path) -> tuple[dict[str, Any], Experiment, list[dict[str, float]]]:
    """Load one case's metadata, configuration and reference summary."""
    meta = yaml.safe_load((path / "case.yaml").read_text(encoding="utf-8"))
    experiment = Experiment.from_yaml(path / "config.yaml")
    summary = json.loads((path / "expected" / "summary.json").read_text("utf-8"))
    return meta, experiment, summary


CASE_DIRS = case_dirs()
CASE_IDS = [p.name for p in CASE_DIRS]


# --------------------------------------------------------------------------
# Corpus integrity. These must pass now -- they check the specification
# itself, not the implementation.
# --------------------------------------------------------------------------


def test_the_corpus_is_not_empty() -> None:
    assert CASE_DIRS, f"no conformance cases found in {CASES_DIR}"


def test_manifest_matches_the_cases_on_disk() -> None:
    assert manifest()["case_count"] == len(CASE_DIRS)


@pytest.mark.parametrize("case_dir", CASE_DIRS, ids=CASE_IDS)
def test_case_config_is_valid_and_complete(case_dir: Path) -> None:
    """Every case must load, validate, and carry a non-empty reference."""
    meta, experiment, summary = load_case(case_dir)

    assert meta["tier"] in {"A", "B"}
    assert meta["exercises"], "every case must say what it is for"
    assert summary, "reference summary is empty"
    assert len(summary) == len(experiment.wedges), (
        "reference has a different number of wedges than the configuration"
    )


@pytest.mark.parametrize("case_dir", CASE_DIRS, ids=CASE_IDS)
def test_case_round_trips_through_the_legacy_emitter(case_dir: Path) -> None:
    """The .txt handed to the reference is derived from this same config.

    If emission is not deterministic, the reference outputs do not correspond
    to the committed configuration and every conformance result below is
    meaningless.
    """
    _, experiment, _ = load_case(case_dir)
    assert experiment.to_raddose_txt() == experiment.to_raddose_txt()
    assert "Crystal" in experiment.to_raddose_txt()


def test_escape_tiering_is_consistent() -> None:
    """A case that enables escape modelling must be tier B, and vice versa."""
    for case_dir in CASE_DIRS:
        meta, experiment, _ = load_case(case_dir)
        expected_tier = "B" if experiment.crystal.escape.any_enabled else "A"
        assert meta["tier"] == expected_tier, (
            f"{case_dir.name} is tier {meta['tier']} but escape.any_enabled is "
            f"{experiment.crystal.escape.any_enabled}"
        )


def test_tier_a_cases_have_no_random_dependence() -> None:
    """Tier A must be reproducible without matching the reference's RNG."""
    tier_a = [d for d in CASE_DIRS if load_case(d)[0]["tier"] == "A"]
    assert tier_a, "the corpus has no deterministic cases"
    for case_dir in tier_a:
        _, experiment, _ = load_case(case_dir)
        assert not experiment.crystal.escape.any_enabled


# --------------------------------------------------------------------------
# The conformance comparison itself. xfail until the solver exists.
# --------------------------------------------------------------------------


def compute_summary(experiment: Experiment) -> list[dict[str, float]]:
    """Run the Python implementation and return a comparable summary.

    Parameters
    ----------
    experiment : Experiment
        The case configuration.

    Returns
    -------
    list[dict[str, float]]
        One dict per wedge, keyed as the reference JSON is.

    Raises
    ------
    NotImplementedError
        If the case asks for something not ported.
    """
    return [summary.as_dict() for summary in solve(experiment)]


def tolerance_for(tier: str, field: str, manifest_data: dict[str, Any]) -> float:
    """Relative tolerance for one field of one tier.

    Parameters
    ----------
    tier : str
        ``"A"`` or ``"B"``.
    field : str
        Summary field name.
    manifest_data : dict[str, Any]
        The parsed manifest.

    Returns
    -------
    float
        Relative tolerance.
    """
    tolerances = manifest_data["tolerances"]
    if tier == "B":
        return float(tolerances["tier_B_relative"])
    if field in set(manifest_data["quantised_quantities"]):
        return float(tolerances["tier_A_quantised_quantities_relative"])
    return float(tolerances["tier_A_relative"])


def unported_reason(experiment: Experiment) -> str | None:
    """Why the port cannot run this case, or ``None`` if it can.

    Read from the configuration rather than a list of case names, so that a
    case stops being excused as soon as the gap it names is filled.

    Parameters
    ----------
    experiment : Experiment
        The case configuration.

    Returns
    -------
    str | None
        A reason, or ``None``.
    """
    if experiment.crystal.escape.any_enabled:
        return "photoelectron and fluorescence escape are Monte Carlo, not ported"
    if experiment.crystal.decay_model == "leal":
        return "the Leal et al. decay model is not ported"
    return None


def _case_params() -> list[Any]:
    """Case directories, with an xfail marker on the ones not ported."""
    params = []
    for case_dir in CASE_DIRS:
        reason = unported_reason(load_case(case_dir)[1])
        marks = (
            [pytest.mark.xfail(reason=reason, raises=NotImplementedError, strict=True)]
            if reason
            else []
        )
        params.append(pytest.param(case_dir, marks=marks, id=case_dir.name))
    return params


CASE_PARAMS = _case_params()


@pytest.mark.parametrize("case_dir", CASE_PARAMS)
def test_matches_reference(case_dir: Path) -> None:
    """Compare the Python result against the Java reference.

    Reports the worst relative deviation seen, not merely pass/fail: a case
    sitting just inside tolerance is telling you something that a green tick
    would hide.
    """
    meta, experiment, expected = load_case(case_dir)
    actual = compute_summary(experiment)
    tolerances = manifest()

    assert len(actual) == len(expected)

    worst_field, worst_deviation = "", 0.0
    failures: list[str] = []
    for index, (exp_row, act_row) in enumerate(zip(expected, actual, strict=True)):
        for field, exp_value in exp_row.items():
            act_value = act_row[field]
            scale = max(abs(exp_value), 1e-30)
            deviation = abs(act_value - exp_value) / scale
            if deviation > worst_deviation:
                worst_field, worst_deviation = f"wedge {index} {field}", deviation
            limit = tolerance_for(meta["tier"], field, tolerances)
            if deviation > limit:
                failures.append(
                    f"wedge {index} {field}: expected {exp_value!r}, got "
                    f"{act_value!r} (relative {deviation:.3e} > {limit:.1e})"
                )

    record_agreement(case_dir.name, worst_deviation, worst_field)
    assert not failures, "\n".join(failures)
